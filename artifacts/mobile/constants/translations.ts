// ── Template helper ────────────────────────────────────────────────────────────
export function interpolate(str: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce((s, [k, v]) => s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v)), str);
}
